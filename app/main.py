"""HTTP API.

uvicorn app.main:app --reload        # development
open http://localhost:8000           # web page
open http://localhost:8000/docs      # interactive API docs (Swagger), generated by FastAPI
"""

from __future__ import annotations

import logging
import time
from contextlib import asynccontextmanager
from pathlib import Path

import requests
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pgvector.psycopg import register_vector
from psycopg_pool import ConnectionPool
from pydantic import BaseModel, Field

from app.answer import AnswerError, answer_question
from app.config import DATABASE_URL
from app.embeddings import embed_query
from app.llm import get_llm
from app.retrieve import retrieve

log = logging.getLogger("app.main")
STATIC = Path(__file__).parent / "static"


# ---------------------------------------------------------------- request / response shapes


class AskRequest(BaseModel):
    question: str = Field(
        min_length=3, max_length=500, examples=["How does tau PET differ from amyloid PET?"]
    )


class Source(BaseModel):
    pmid: str
    title: str
    journal: str
    year: int | None
    url: str
    score: float


class Timings(BaseModel):
    retrieval_ms: float
    llm_ms: float


class AskResponse(BaseModel):
    question: str
    found: bool
    answer: str
    sources: list[Source]
    model: str
    attempts: int
    timings: Timings


# ---------------------------------------------------------------- app lifecycle


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Expensive things happen once at startup, not on every request:
    #   - load the embedding model (~7 s)
    #   - open a pool of database connections (opening a connection costs a network round trip)
    #   - create the LLM client (fails fast if the API key is missing)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")
    embed_query("warm-up")
    app.state.pool = ConnectionPool(
        DATABASE_URL, min_size=1, max_size=5, configure=register_vector, open=True
    )
    app.state.llm = get_llm()
    log.info("ready: llm=%s", app.state.llm.name)
    yield
    app.state.pool.close()


app = FastAPI(title="NeuroLit", version="0.1.0", lifespan=lifespan)


# ---------------------------------------------------------------- endpoints


@app.get("/", include_in_schema=False)
def index() -> FileResponse:
    return FileResponse(STATIC / "index.html")


@app.get("/health")
def health() -> dict:
    """Liveness + readiness: is the database reachable and does it hold data?"""
    try:
        with app.state.pool.connection(timeout=3) as conn:
            chunks = conn.execute("SELECT count(*) FROM chunks").fetchone()[0]
    except Exception as exc:  # noqa: BLE001 - any failure means "not healthy"
        raise HTTPException(503, f"database unavailable: {type(exc).__name__}") from exc
    return {"status": "ok", "chunks": chunks, "llm": app.state.llm.name}


# Plain `def` (not async): FastAPI runs it in a worker thread, so a slow LLM call
# does not block other requests.
@app.post("/ask", response_model=AskResponse)
def ask(req: AskRequest) -> AskResponse:
    question = req.question.strip()

    t0 = time.perf_counter()
    with app.state.pool.connection() as conn:
        passages = retrieve(conn, question)
    t1 = time.perf_counter()

    try:
        result = answer_question(question, passages, app.state.llm)
    except AnswerError as exc:
        # The model kept producing invalid or badly cited answers: refuse rather than show it.
        log.warning("refused answer for %r: %s", question, exc)
        raise HTTPException(
            502, "The model could not produce a properly cited answer. Try rephrasing."
        ) from exc
    except requests.RequestException as exc:
        log.error("LLM provider error: %s", exc)
        raise HTTPException(503, "The language model service is unavailable. Try again shortly.") from exc
    t2 = time.perf_counter()

    return AskResponse(
        question=question,
        found=result.found,
        answer=result.answer,
        sources=[
            Source(
                pmid=p.pmid, title=p.title, journal=p.journal, year=p.year, url=p.url, score=round(p.score, 3)
            )
            for p in result.sources
        ],
        model=result.model,
        attempts=result.attempts,
        timings=Timings(retrieval_ms=round(1000 * (t1 - t0), 1), llm_ms=round(1000 * (t2 - t1), 1)),
    )
